// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen, act, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import type { GanCubeEvent } from 'gan-web-bluetooth';
import { IDBFactory } from 'fake-indexeddb';
import { LiveApp } from './LiveApp';
import { LocalRepository } from '../adapters/local-repository';
import { SOLVED } from '../domain/cube';
import { validateScramble } from '../domain/scramble';
import type { Connection } from '../domain/session';
vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} });
afterEach(() => { cleanup(); window.location.hash = ''; });
it('cancels pre-solve navigation, finalizes active navigation once as DNF, and owns one connection', async () => {
  let next: (event: GanCubeEvent) => void = () => {};
  let serial = 10;
  const subscribe = vi.fn((observer: { next: (event: GanCubeEvent) => void }) => { next = observer.next; return { unsubscribe: vi.fn() }; });
  const connection: Connection = { deviceName: 'test', events$: { subscribe }, disconnect: vi.fn(async () => {}), sendCubeCommand: async () => {} };
  const repository = new LocalRepository(new IDBFactory());
  render(<LiveApp connectCube={async () => connection} repository={repository} bluetoothAvailable generateScramble={async () => validateScramble('R2')} />);
  await screen.findByRole('option', { name: 'Default' });
  fireEvent.click(screen.getByRole('button', { name: 'Connect Cube' }));
  await screen.findByRole('button', { name: 'Connected' });
  act(() => next({ type: 'FACELETS', timestamp: 1, serial, facelets: SOLVED, state: { CP: [], CO: [], EP: [], EO: [] } }));
  const physical = (move: string): void => { act(() => next({ type: 'MOVE', timestamp: 1, serial: ++serial, move, face: 1, direction: move.endsWith("'") ? 1 : 0, localTimestamp: 1, cubeTimestamp: 1 })); };
  await screen.findByLabelText('Actual setup moves');
  await screen.findByLabelText('Actual setup moves');
  if (screen.queryByRole('dialog')) fireEvent.click(screen.getByRole('button', { name: 'Close' }));
  fireEvent.click(screen.getByRole('link', { name: 'Insights' }));
  await waitFor(async () => expect(await repository.listCheckpoints()).toEqual([]));
  expect(await repository.listTimedResults()).toEqual([]);
  fireEvent.click(screen.getByRole('link', { name: 'Cube Trainer' }));
  await screen.findByLabelText('Actual setup moves');
  await screen.findByLabelText('Actual setup moves');
  physical('R'); physical('R'); physical("R'");
  expect(screen.getByRole('timer')).toBeTruthy();
  fireEvent.click(screen.getByRole('link', { name: 'Settings' }));
  if (screen.queryByRole('dialog')) fireEvent.click(screen.getByRole('button', { name: 'Close' }));
  fireEvent.click(screen.getByRole('link', { name: 'Insights' }));
  await waitFor(async () => expect(await repository.listTimedResults()).toHaveLength(1));
  expect((await repository.listTimedResults())[0]).toMatchObject({ status: 'completed', penalty: 'dnf' });
  expect(subscribe).toHaveBeenCalledOnce();
  expect(connection.disconnect).not.toHaveBeenCalled();
});
