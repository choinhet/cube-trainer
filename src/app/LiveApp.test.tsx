  expect(screen.getByText(/The reported cube is unsolved/)).toBeTruthy();
  expect(screen.getByLabelText('Live 3D cube').getAttribute('data-state')).toBe(scrambled);
  quarters(15); // Batched false->true still starts a fresh confirmation.
  expect((screen.getByRole('checkbox') as HTMLInputElement).checked).toBe(false);
  fireEvent.click(screen.getByRole('checkbox'));
  act(() => deliver({ type: 'DISCONNECT', timestamp: 3 }));
